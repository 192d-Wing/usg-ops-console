// Builds the single-file vendored SDK text from src/. Pure function over
// the source texts so the tests can run it without Node APIs.
import { sha256Hex } from "./check.mjs";

/** Concatenation order; index.ts only re-exports and is not included. */
export const BUNDLE_FILES = ["version.ts", "protocol.ts", "transport.ts"];

const LOCAL_IMPORT = /^import (?:type )?\{[^}]*\} from "\.\/[a-z]+\.js";\s*$/;

/**
 * @param {Record<string, string>} sources file name -> contents, for BUNDLE_FILES
 * @param {{ version: string, protocol: number, source: string }} meta
 * @returns {Promise<string>} header line + body
 */
export async function bundle(sources, meta) {
  const parts = [
    "// Generated by usg-ops-console sdk-js/scripts/vendor.mjs. Do not edit; re-run the vendor script.",
    "/* eslint-disable */",
  ];
  for (const f of BUNDLE_FILES) {
    const text = sources[f];
    if (typeof text !== "string") throw new Error(`bundle: missing ${f}`);
    const lines = text.split("\n");
    for (const l of lines) {
      if (/^import /.test(l) && !LOCAL_IMPORT.test(l)) throw new Error(`bundle: ${f} has a non-local import: ${l}`);
    }
    parts.push(`\n// ---- ${f} ----`, lines.filter((l) => !LOCAL_IMPORT.test(l)).join("\n").trimEnd());
  }
  const body = parts.join("\n") + "\n";
  const digest = await sha256Hex(body);
  return `// @usg-ops-console/sdk-js ${meta.version} protocol=${meta.protocol} source=${meta.source} sha256=${digest}\n${body}`;
}
