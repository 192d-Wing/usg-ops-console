// M4 tool registries: deploy/compose/tools/registry.*.toml with ${CONSOLE_*}
// placeholders rendered from ports.env (+ env overrides) into target/.
const REPO = resolve(import.meta.dirname, "..");
function renderRegistry(name: string): string {
  const src = readFileSync(`${REPO}/deploy/compose/tools/registry.${name}.toml`, "utf8");
  const out = src.replace(/\$\{(CONSOLE_[A-Z0-9_]+)\}/g, (_, k: string) => String(port(k)));
  const dir = `${REPO}/target/e2e-tools`;
  mkdirSync(dir, { recursive: true });
  writeFileSync(`${dir}/registry.${name}.e2e.toml`, out);
  return `${dir}/registry.${name}.e2e.toml`;
}
